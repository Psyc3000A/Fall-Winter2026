import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

# Load OCD research data from GitHub
url = "https://raw.githubusercontent.com/Psyc3000A/Fall-Winter2026/refs/heads/main/EMA_data_new.csv"
df = pd.read_csv(url)

# Select the variables
data = df[["Confidence", "Anxiety", "OCD"]].copy()

# Convert responses to numeric values
for col in ["Confidence", "Anxiety", "OCD"]:
    data[col] = pd.to_numeric(data[col], errors="coerce")

# Remove responses missing any of these ratings
data = data.dropna()

# Create descriptive results table
table = data.groupby("Confidence").agg(
    N=("OCD", "count"),
    Average_OCD=("OCD", "mean"),
    Average_Anxiety=("Anxiety", "mean")
).reset_index()

table = table.round(2)

print("TABLE: OCD and Anxiety by Confidence Rating")
print(table)

# Save the table
table.to_csv("ocd_ema_summary.csv", index=False)

# Create the graph
sns.set_theme(style="whitegrid")

plt.figure(figsize=(8, 5))

sns.barplot(
    data=data,
    x="Confidence",
    y="OCD",
    errorbar=None,
    color="steelblue"
)

plt.title("Average OCD Severity by Confidence Rating")
plt.xlabel("Confidence Rating")
plt.ylabel("Average OCD Severity")
plt.ylim(0, 4)
plt.tight_layout()

# Save the graph
plt.savefig("ocd_ema_figure.png", dpi=300)
plt.show()